#!/usr/bin/env node
/* 生成 api/academy/events-data.js：平台实操事件的闭合清单，来自课程包 frontend/src/lib/lessons-data.js
 * 每关的 event 字段。服务端收 POST /api/events 时只认这张表上的事件名。
 *
 *   node scripts/build-academy-events.mjs           # 写
 *   node scripts/build-academy-events.mjs --check   # 过期即失败（CI）
 *
 * 与 build-coach-assets.mjs 同一种安排：api 不去 import frontend/，产物生成后提交。 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'api', 'academy', 'events-data.js');
const check = process.argv.includes('--check');

// 走 lessons.js 而不是 lessons-data.js：领域路径（lessons-extra.js）也要进索引
const LS = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'lessons.js')).href);
const D = { PATHS: Object.fromEntries(LS.PATH_KEYS.map(p => [p, LS.levelsOf(p)])), ROLES: LS.ROLES, PATHN: LS.PATH_NAMES };
const events = {};
for (const path of Object.keys(D.PATHS)) {
  D.PATHS[path].forEach((l, i) => {
    const e = l.type === 'practice' || l.type === 'seminar' ? '' : String(l.event || '').trim();
    if (e) (events[e] = events[e] || []).push(`${path}-${i}`);
  });
}
// 看板要的课程索引：路径长度、岗位→路径、关卡标题
const PATH_LEN = {}, LEVELS = {}, LEVEL_TYPES = {}, RUBRICS = {};
for (const path of Object.keys(D.PATHS)) {
  PATH_LEN[path] = D.PATHS[path].length;
  D.PATHS[path].forEach((l, i) => {
    const lv = LS.levelOf(`${path}-${i}`);
    LEVELS[`${path}-${i}`] = lv.title;
    LEVEL_TYPES[`${path}-${i}`] = lv.type;
    if (lv.rubric) RUBRICS[`${path}-${i}`] = lv.rubric;
  });
}
const ROLE_PATH = Object.fromEntries(Object.entries(D.ROLES).map(([r, v]) => [r, v.path]));
const body = '/* GENERATED by scripts/build-academy-events.mjs from frontend/src/lib/lessons-data.js — do not edit. */\n' +
  `export const GENERATED_FROM = 'frontend/src/lib/lessons-data.js';\n` +
  '/** 事件名 → 用到它的关卡 id。 */\n' +
  'export const EVENTS = Object.freeze(' + JSON.stringify(events, null, 2) + ');\n' +
  '/** 路径 → 关数；岗位 → 路径；关卡 id → 标题；路径名。 */\n' +
  'export const PATH_LEN = Object.freeze(' + JSON.stringify(PATH_LEN) + ');\n' +
  'export const ROLE_PATH = Object.freeze(' + JSON.stringify(ROLE_PATH) + ');\n' +
  'export const PATH_NAMES = Object.freeze(' + JSON.stringify(D.PATHN) + ');\n' +
  'export const LEVELS = Object.freeze(' + JSON.stringify(LEVELS) + ');\n' +
  '/** 关卡 id → tool | practice | seminar；实践关与研讨关的点评量表。 */\n' +
  'export const LEVEL_TYPES = Object.freeze(' + JSON.stringify(LEVEL_TYPES) + ');\n' +
  'export const RUBRICS = Object.freeze(' + JSON.stringify(RUBRICS) + ');\n';

const rel = out.slice(root.length + 1);
if (check) {
  let current = null;
  try { current = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== body) { console.error(`${rel} is out of date — run: node scripts/build-academy-events.mjs`); process.exit(1); }
  console.log(`${rel} in sync (${Object.keys(events).length} events).`);
} else {
  writeFileSync(out, body);
  console.log(`Wrote ${rel} — ${Object.keys(events).length} events.`);
}
